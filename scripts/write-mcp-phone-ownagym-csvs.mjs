function csvEscape(cell) {
  const s = cell == null ? '' : String(cell);
  if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

function toCsv(values) {
  return values.map((row) => (row ?? []).map(csvEscape).join(',')).join('\n');
}

